// Реестр «сессия протухла» — мост между модулями БЕЗ доступа к React-контексту
// и провайдером сессии (tracker #1011).
//
// Зачем он нужен. `invalidate()` до этой карточки звался ровно из ОДНОГО места
// — `lib/live.tsx`, на 401 SSE-стрима. А `/v1/events/stream` аутентифицируется
// один раз на коннекте и дальше держит вечный цикл с keepalive: кука,
// протухшая ПОД ЖИВЫМ стримом, логаут не вызывала вовсе — до обрыва
// соединения. Всё это время панель оставалась полуразлогиненной: графики
// молча сталые, каждый новый запрос — 401, и ни одна дверь не вела на логин.
//
// Точки выхода в сеть (`request()` в api.ts, `fetchVM()` в metrics.ts) —
// простые модули, а не компоненты, и `useSession()` им недоступен. Реестр
// разрывает это, оставаясь односторонним: сюда только СООБЩАЮТ факт, решение
// принимает провайдер.
//
// Модуль намеренно ни от чего не зависит — иначе с `api.ts` и `session.tsx`
// получился бы цикл импорта.

type Listener = () => void;

const listeners = new Set<Listener>();

/**
 * Подписаться на «сессия протухла». Зовёт `SessionProvider`; возвращает
 * отписку (StrictMode монтирует эффекты дважды, поэтому Set, а не одиночный
 * слот: две регистрации не затирают друг друга и обе честно снимаются).
 */
export function onSessionExpired(fn: Listener): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/**
 * Сообщить, что master ответил 401. Зовётся из обработчиков ответа; подписчика
 * может не быть вовсе (юнит-тест модуля без провайдера) — это штатно и молча.
 */
export function notifySessionExpired(): void {
  for (const fn of [...listeners]) fn();
}
