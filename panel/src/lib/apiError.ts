// Единый перевод отказа REST-API мастера в текст для оператора (tracker #1005).
//
// ПРАВИЛО, ради которого модуль существует: `ApiError.detail` — свободная проза
// мастера, английская и не переводимая, и в DOM панели ей места нет
// (`docs/specs/panel.md` §1 п.6 — «панель 100% EN+RU, сквозных строк мастера
// нет»). До #1005 восемнадцать мест писали `e.detail ?? e.code` прямо в
// состояние компонента, поэтому привязанный ключ читал в русском интерфейсе
// буквально `key is bound to game/dev`.
//
// Механизм тот же, что #996 дал графикам (`MetricMessage.errorText`): наружу
// выходит МАШИННЫЙ КОД и текст каталога, а не тело ответа. Разница только в
// поверхности — там метрик-проксия, здесь весь остальной REST. Гарантия здесь
// СТРУКТУРНАЯ, а не дисциплинарная: во всей функции нет ветки, которая читала
// бы `e.detail`, поэтому новая поверхность не может «случайно» его показать —
// ей пришлось бы не звать `apiErrorMessage` вовсе (это ловит guard-тест
// `test/apiErrorText.test.ts`).
//
// Код панель показывает СОЗНАТЕЛЬНО: он не переводится наравне с semver и id
// (та же §1 п.6) и остаётся единственным, за что оператор может зацепиться в
// баг-репорте. Изъять и его значило бы обменять одну беду («непонятная
// английская фраза») на другую («совсем нечего сказать в тикете»).

import { ApiError } from './api';
import type { I18nContextValue, MessageKey } from './i18n';

export interface ApiErrorTexts {
  /**
   * Текст отказа ПО ПРИВЯЗКЕ ключа — результат `useBindingRefusal()`, то есть
   * `undefined` у непривязанного ключа. Передавайте его на любой поверхности,
   * где 403 достижим: без него привязанный ключ снова получит диагноз про
   * скоуп, который #1000 объявил ложью.
   */
  refusal?: string | undefined;
  /**
   * 403 у НЕпривязанного ключа. Дефолт `ui.err.forbidden` («нужен readonly или
   * admin») верен для ЧТЕНИЙ; поверхность ДЕЙСТВИЯ обязана передать свой ключ
   * (`confirm.err.forbidden`), иначе назовёт не тот скоуп: действию нужен
   * deploy/admin, а не readonly.
   */
  forbidden?: MessageKey;
  /**
   * Не-`ApiError` (запрос не дошёл: сеть, CORS, оборванное соединение).
   * Дефолт — `ui.err.offline`.
   */
  generic?: MessageKey;
  /**
   * Свои тексты для статусов, где действие оператора ОТЛИЧАЕТСЯ от «сообщите о
   * поломке»: 404 «уже удалено», 409 «конфликт состояния» и т.п. Всё, чего тут
   * нет, получает общий текст с кодом — так и задумано, см. `CODE_MESSAGE` в
   * `MetricMessage.tsx`.
   */
  byStatus?: Partial<Record<number, MessageKey>>;
}

/**
 * Отказ API → строка для оператора. Чистая функция: `t` передаётся аргументом,
 * поэтому её зовут и из компонентов, и из юнит-тестов без рендера.
 *
 * Порядок веток не случаен и менять его нельзя:
 *   1. не `ApiError` — ответа не было вовсе, коду взяться неоткуда;
 *   2. 401 — единственный код, где действие оператора своё: войти заново;
 *   3. 403 — привязка ключа СПЕЦИФИЧНЕЕ скоупа, поэтому проверяется раньше
 *      `byStatus` (иначе поверхность со своим 403-текстом молча вернула бы
 *      ложный диагноз привязанному ключу — ровно дефект #1010);
 *   4. свой текст поверхности по статусу;
 *   5. общий текст с машинным кодом.
 */
export function apiErrorMessage(
  e: unknown,
  t: I18nContextValue['t'],
  texts: ApiErrorTexts = {},
): string {
  if (!(e instanceof ApiError)) return t(texts.generic ?? 'ui.err.offline');
  if (e.status === 401) return t('ui.err.expired');
  if (e.status === 403) return texts.refusal ?? t(texts.forbidden ?? 'ui.err.forbidden');
  const own = texts.byStatus?.[e.status];
  return own !== undefined ? t(own) : t('ui.err.code', { code: e.code });
}
