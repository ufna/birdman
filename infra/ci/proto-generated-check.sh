#!/usr/bin/env bash
# Гейт «сгенерированное совпадает с исходником» для proto/ (tracker #1110).
#
#   infra/ci/proto-generated-check.sh [repo-root]
#
# Зовётся ПОСЛЕ регенерации (`.github/workflows/proto.yml`: собрать
# `proto/protogen.Dockerfile` → `buf generate`) и отвечает ровно на один
# вопрос: воспроизвела ли генерация ровно то, что лежит в git. Сам он ничего
# не генерирует — потому и тестируется без докера.
#
# ЗАЧЕМ. `proto/agentlink/v1/*.pb.go` ЗАКОММИЧЕНЫ (потребителям Go-модуля
# генератор не нужен), а генерируются локально через buf. До этого гейта
# сверки не было ни одной: grep по `.github/workflows/*` на
# `buf|protoc|protobuf|go generate|generate` давал единственное попадание —
# комментарий про `BufferEmptyReady` в `infra.yml`. Значит молча разъезжались
# правка `.proto` без регенерации, регенерация другой версией плагина и любой
# хенд-эдит в `.pb.go`; обнаруживал это случайный человек, следующим
# запустивший генерацию и получивший в диффе неожиданный шум.
#
# ПОЧЕМУ ГЕЙТ ЧЕСТНЫЙ, А НЕ СВЕРКА КОММЕНТАРИЕВ. Дешёвая альтернатива —
# сверять leading-комментарии одноимённых messages — ловит один класс разъезда
# из трёх и при этом ВЫГЛЯДИТ как «файлы сверены». Это ровно то «выглядит
# покрытым», против чего написана шапка infra/ci/tests/run.sh.
#
# ПОЧЕМУ ЛОЖНЫЙ КРАСНЫЙ ЗДЕСЬ НЕ ЖДЁТСЯ (замер, не рассуждение). Главный довод
# против честного гейта — «разные версии protoc-gen-go дают разный вывод».
# Проверено в лоб на #1110: пинованный тулчейн (`buf 1.55.1`,
# `protoc-gen-go@v1.36.6`, `protoc-gen-go-grpc@v1.5.1`) воспроизвёл оба
# закоммиченных файла ПОБАЙТОВО — причём плагины собирались Go 1.26.5, тогда
# как `protogen.Dockerfile` пинует `golang:1.24`. То есть вывод определяется
# пином ПЛАГИНА, а не тулчейном, которым плагин собран, и плавающий базовый
# образ форматирование не сдвигает. Пины при этом живут В ОДНОМ месте —
# в `protogen.Dockerfile`, который workflow и собирает: продублируй их в YAML,
# и гейт сам стал бы генератором ложного красного (бампнули Dockerfile — CI
# продолжает требовать вывод старого генератора).
#
# ДВЕ ДЫРЫ КЛАССА «МОЛЧА ЗЕЛЁНЫЙ» ЗАКРЫТЫ ЯВНО:
#   1. `git status --porcelain -uall`, а не `git diff --exit-code`: новый
#      `.proto`, чей `.pb.go` забыли закоммитить, даёт UNTRACKED-файл, который
#      `git diff` не видит вовсе;
#   2. приёмка не бывает пустой — нет НИ ОДНОГО трекнутого `*.pb.go`, значит
#      проверять нечего и «зелёное» ничего не значит: это громкий отказ.
#      (Ту же роль на стороне workflow играет удаление `*.pb.go` ПЕРЕД
#      генерацией: генерация, не произведшая ничего и вышедшая нулём, даёт
#      удаления — красное, а не чистое дерево.)
set -euo pipefail

root="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

if ! git -C "$root" rev-parse --git-dir >/dev/null 2>&1; then
	echo "ERROR: $root — не git-репозиторий, сверять нечего" >&2
	exit 2
fi

# Приёмка не должна быть пустой (см. шапку, пункт 2).
tracked="$(git -C "$root" ls-files -- 'proto/**/*.pb.go')"
if [ -z "$tracked" ]; then
	echo "ERROR: под proto/ нет ни одного трекнутого *.pb.go." >&2
	echo "       Сгенерированные файлы закоммичены СОЗНАТЕЛЬНО (proto/README.md)," >&2
	echo "       и без них этот гейт зеленел бы ни на чём. Раскладка уехала или" >&2
	echo "       файлы снесены — разберитесь, это не повод пройти молча." >&2
	exit 1
fi

dirty="$(git -C "$root" status --porcelain -uall -- proto)"
if [ -n "$dirty" ]; then
	echo "ERROR: сгенерированный код разошёлся с исходником." >&2
	echo >&2
	echo "Регенерация пинованным тулчейном изменила дерево под proto/ —" >&2
	echo "значит закоммиченное НЕ является выводом генератора для текущих" >&2
	echo ".proto. Обычные причины: правка .proto без регенерации; хенд-эдит" >&2
	echo "в .pb.go; новый .proto, чей .pb.go забыли закоммитить." >&2
	echo >&2
	echo "Разошлось (git status --porcelain -uall -- proto):" >&2
	printf '%s\n' "$dirty" | sed 's/^/  /' >&2
	echo >&2
	echo "Дифф трекнутых файлов:" >&2
	git -C "$root" --no-pager diff -- proto | sed 's/^/  /' >&2
	echo >&2
	echo "Чинится регенерацией и коммитом результата (proto/README.md):" >&2
	echo "  cd proto" >&2
	echo "  docker build -t birdman-protogen -f protogen.Dockerfile ." >&2
	echo "  docker run --rm -v \"\$PWD\":/workspace birdman-protogen generate" >&2
	exit 1
fi

echo "ok: сгенерированный код под proto/ совпадает с выводом пинованного генератора"
