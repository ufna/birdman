#!/usr/bin/env bash
# Гейт «в репозитории нет трекнутых исполняемых артефактов» (tracker #1112).
#
#   infra/ci/no-tracked-binaries.sh [repo-root]
#
# Отвечает ровно на один вопрос: не лежит ли под git'ом файл, чьё СОДЕРЖИМОЕ —
# скомпилированный исполняемый формат. Ничего не собирает и не генерирует,
# поэтому докер ему не нужен и тестируется он без него.
#
# ЗАЧЕМ. 12.08 коммитом `bebbbac` (про allocate-metadata, к бинарю отношения не
# имевшим) в индекс случайным `git add` уехал `sdk/mockagent/mockagent` — 4.2 МБ
# ELF, результат `go build` без `-o`, запущенного прямо в каталоге модуля. Его
# не брал НИ ОДИН потребитель (smoke.sh, README и CMakeLists собирают mockagent
# заново во временный каталог), но он уже успел разойтись с репозиторием:
# собран go1.26.5 против пина `go-version: '1.24'` во всех пяти workflow'ах,
# `CGO_ENABLED=1` и `not stripped` против канона `CGO_ENABLED=0 -trimpath
# -ldflags '-s -w'`, а внутрь был вкомпилирован абсолютный путь другого чекаута
# владельца (`/w/khl/birdman/...`) — для публичного OSS-репозитория мелкая, но
# настоящая утечка. Единственным шагом CI про mockagent был `go vet ./...`, то
# есть содержимое бинаря не сверялось ни с чем: уехал бы `main.go` вперёд — не
# заметил бы никто. Тот же класс «выглядит покрытым», что закрывала #1110.
#
# ПОЧЕМУ СИГНАЛ — МАГИЯ СОДЕРЖИМОГО, А НЕ БИТ РЕЖИМА (замер, не рассуждение).
# На дереве #1112 трекнутых файлов с режимом `100755` — 19, и 18 из них обычные
# скрипты (`master/build.sh`, раннеры тестов ролей, чекеры этого же каталога).
# Гейт по биту режима краснил бы на них всех и был бы обойдён в первый же день.
# Трекнутых файлов с магией исполняемого формата при этом ровно ОДИН — тот
# самый `sdk/mockagent/mockagent`; прочие трекнутые бинарники репозитория — два
# PNG в `docs/images/`, и никакая магия ниже их не матчит. То есть ложных
# срабатываний на сегодняшнем дереве ноль, а скрипты гейт не трогает вовсе.
#
# ПОЧЕМУ БЕЗ СПИСКА ИСКЛЮЧЕНИЙ. Дешёвая добавка — allowlist «этот бинарь можно»
# — сделала бы гейт молча обходимым: строчка в списке не видна в диффе так, как
# видна правка самого гейта. Легитимная нужда закоммитить бинарь (фикстура,
# например) лечится правкой ЭТОГО файла — актом видимым и ревьюируемым. Ровно
# та же логика, что в шапке infra/ci/tests/run.sh: гейт, который можно тихо
# выключить, хуже отсутствующего.
#
# ГРАНИЦА, ЧЕСТНО. Читается РАБОЧЕЕ ДЕРЕВО по списку трекнутых путей, а не блоб
# из индекса. На чистом чекауте (то есть на CI) это одно и то же; локально же
# чтение дерева ещё и полезнее — видно то, что вот-вот уедет в коммит.
# Симлинки и гитлинки пропускаются по РЕЖИМУ из `ls-files -s`: содержимое
# симлинка в git'е — строка с путём, а не ELF, на который он показывает.
set -euo pipefail

root="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

if ! git -C "$root" rev-parse --git-dir >/dev/null 2>&1; then
	echo "ERROR: $root — не git-репозиторий, проверять нечего" >&2
	exit 2
fi

# Приёмка не бывает пустой: ноль трекнутых файлов — это не «чисто», это сломанная
# раскладка, на которой зелёное не значит ничего (тот же пункт, что у
# proto-generated-check.sh).
if [ -z "$(git -C "$root" ls-files)" ]; then
	echo "ERROR: в $root нет НИ ОДНОГО трекнутого файла — проверять нечего," >&2
	echo "       и «зелёное» здесь ничего не значило бы. Раскладка уехала." >&2
	exit 2
fi

# Магия исполняемых форматов. Первые 8 байт файла в hex без разделителей.
magic_kind() {
	case "$1" in
		7f454c46*) echo "ELF (Linux/BSD executable)" ;;
		cffaedfe* | cefaedfe* | fefaedcf* | fefaedce*) echo "Mach-O (macOS executable)" ;;
		cafebabe*) echo "Mach-O universal / Java class" ;;
		4d5a*) echo "PE/DOS (.exe/.dll)" ;;
		213c6172*) echo "ar (статическая библиотека)" ;;
		*) echo "" ;;
	esac
}

found=0
while IFS= read -r -d '' entry; do
	# Формат `ls-files -s`: "<режим> <sha> <stage>\t<путь>".
	meta="${entry%%$'\t'*}"
	path="${entry#*$'\t'}"
	mode="${meta%% *}"

	# Только обычные файлы: 120000 — симлинк, 160000 — гитлинк (см. шапку).
	case "$mode" in
	100644 | 100755) ;;
	*) continue ;;
	esac

	file="$root/$path"
	# Трекнут, но в дереве его нет — это и есть удаление, то есть лечение.
	if [ ! -f "$file" ]; then
		continue
	fi

	magic="$(od -An -tx1 -N8 "$file" 2>/dev/null | tr -d ' \n')"
	kind="$(magic_kind "$magic")"
	if [ -n "$kind" ]; then
		if [ "$found" -eq 0 ]; then
			echo "ERROR: в индексе лежат скомпилированные исполняемые артефакты:" >&2
		fi
		echo "       $path — $kind" >&2
		found=$((found + 1))
	fi
done < <(git -C "$root" ls-files -s -z)

if [ "$found" -ne 0 ]; then
	echo >&2
	echo "Собранные бинари в git не кладут: они протухают молча (наш случай —" >&2
	echo "sdk/mockagent/mockagent собрался go1.26.5 при пине 1.24 и таскал внутри" >&2
	echo "путь чужой машины), раздувают клон навсегда и никем не сверяются." >&2
	echo "Лечение: git rm --cached <путь> и правило в подходящем .gitignore." >&2
	exit 1
fi

echo "ok: трекнутых исполняемых артефактов нет"
