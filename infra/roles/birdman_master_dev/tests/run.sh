#!/usr/bin/env bash
# Тесты роли birdman_master_dev — LOCAL only, ни один хост не трогается и
# плейбук не гоняется: шаблон compose рендерится настоящим ansible'ом во
# временный каталог. Docker этой сьюте не нужен вовсе (см. ниже почему).
#
#   ./infra/roles/birdman_master_dev/tests/run.sh
#
# Что покрыто (tracker #1089): конфиг, который роль монтирует в контейнер,
# обязан этим контейнером ЧИТАТЬСЯ — тот же критерий, что у остальных ролей с
# composes. Роль мониторинга положила alertmanager.yml 0600 root:root в
# контейнер, бегущий от nobody: краш-луп с рождения, 2380 рестартов за 40
# часов, роль зелёная (#1072).
#
# СЕГОДНЯ ПРОВЕРЯТЬ ТУТ НЕЧЕГО, И ЭТО НЕ ПОВОД НЕ ПРОВЕРЯТЬ: compose мастера
# монтирует ТОЛЬКО именованный том (birdman-pgdata), то есть ни одного
# хостового пути. Отсюда --allow-no-mounts — осознанное «ноль маунтов законно»
# вместо отказа, который сторож даёт по умолчанию (ноль маунтов там, где они
# были, — это сломавшийся рендер). Смысл сьюты в завтрашнем дне: первый же
# bind-маунт, добавленный сюда — конфиг postgres, сертификат, что угодно, —
# автоматически попадёт под критерий, вместо того чтобы приехать молча. Ровно
# в этом состоянии («сегодня правильно, защиты нет») alertmanager прожил 40
# часов.
#
# Docker здесь не нужен именно потому, что маунтов нет: uid образа сторож
# спрашивает живой пробой только у НЕмирочитаемых путей. Появится маунт —
# появится и потребность в docker, и его отсутствие будет громким отказом
# сторожа, а не тихим пропуском.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
role="$(dirname "$here")"
repo="$(cd "$role/../../.." && pwd)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

echo "── render: master compose project"
mkdir -p "$work/one"
ansible-playbook -i birdman-master-test, "$here/render_role.yml" \
  -e "birdman_out=$work/one" >"$work/one/ansible.log" 2>&1 \
  || { cat "$work/one/ansible.log" >&2; fail "рендер compose роли мастера упал"; }

# Порт Postgres — только на loopback: 5432 на общем боксе занят чужим продом, а
# выставленный наружу дев-Postgres мастера — это чужой прод в одном netns с
# нашим. Дешёвая проверка ровно того, что нельзя увидеть по логам роли.
grep -q '"127.0.0.1:5433:5432"' "$work/one/compose.yml" \
  || fail "Postgres мастера отрендерился не на loopback:5433"

# ── конфиг обязан читаться контейнером, в который смонтирован (#1072/#1089) ──
echo "── mounted config access"
"$repo/infra/ci/mounted-config-access.sh" --role "$role" --allow-no-mounts \
  "$work/one/compose.yml"

echo "ALL OK"
