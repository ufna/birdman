-- project — проектное измерение mute'а (мультипроект, tracker #957, шаг 3/3
-- эпика #950). До этой миграции цель mute'а была парой (alertname, region), а
-- после шагов 1–2 один и тот же alertname горит по НЕСКОЛЬКИМ проектам сразу
-- (лейбл project в правилах vmalert, 076c6be): mute без проектного измерения
-- глушил их все разом — оператор проекта А тушил сигнал проекту Б.
--
-- NULL = все проекты, ровно как nullable region = все регионы. Пустая строка
-- НЕ используется как «все»: у алерта пустой project означает «платформенный»
-- (см. alertScope в httpapi/alerts.go), и если бы mute хранил '' вместо NULL,
-- «глушить всё» стало бы неотличимо от «глушить только платформенное».
--
-- Индекса нет намеренно (как и у silence_id в 000016): горячая выборка
-- muted-флага идёт по alertname (индекс из 000004), проект отсеивается уже в
-- Go на нескольких строках активных мьютов.
alter table alert_mutes add column project text;
