-- Сходящийся sweep снятия образов (Фаза D, дефект стенда: гонка disabled×drain).
-- RemoveImage уходил В МОМЕНТ перехода версии в disabled — но disabled-переход
-- случается ровно тогда, когда серверы этой версии ещё дренятся (реконсайлер
-- только что выгнал их из окна, grace 30с). Агент видит образ занятым живым
-- контейнером, скипает команду («in use by a live container — skipped»), через
-- 40-60с контейнеры уходят — а повторить команду НЕКОМУ: промптная очистка не
-- работала в типовом потоке, спасал только watermark-GC (80% диска).
--
-- Маркер даёт реконсайлеру сходящийся 60с-sweep: disabled-версия, у которой уже
-- не осталось живых серверов и ref не держит не-disabled версия того же
-- (project, env), получает РОВНО ОДНУ догоняющую RemoveImage — image_cleanup_at
-- is null → отправили → штамп, поэтому команда не спамится каждый субтик.
-- Немедленная отправка при disabled-переходе остаётся быстрым путём (когда образ
-- уже свободен); маркер её не гасит — sweep именно догоняет гоночный случай.
alter table versions add column image_cleanup_at timestamptz;
