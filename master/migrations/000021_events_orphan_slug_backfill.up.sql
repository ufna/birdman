-- Осиротевшее ДО 000020 событие доатрибутируется по слагу в payload (tracker #1091).
--
-- ЧТО ОСТАВИЛА 000020. Она добавила снимок слага владельца и забэкфиллила его
-- только для ЖИВЫХ строк (`from projects p where p.id = e.project_id`). Строки,
-- осиротевшие РАНЬШЕ (проект удалён до миграции, `project_id` уже обнулён FK),
-- остались с пустым снимком — то есть неотличимы от платформенных ПО РОЖДЕНИЮ,
-- и оба читателя ленты по-прежнему показывают их привязанному ключу ЛЮБОГО
-- проекта. Сама 000020 записала это как «имя владельца нигде не сохранено,
-- восстанавливать не из чего». Утверждение оказалось ШИРЕ правды: у целого
-- класса видов имя владельца лежит в payload — в том самом ключе, из которого
-- читает последняя ветка coalesce'а в 000019 и в `store.insertEvent`.
--
-- ПОЧЕМУ ЭТО ВЫВОД, А НЕ ДОГАДКА. У строки с пустым `project_id` владельца в
-- живых нет — и путей сюда ровно два. Либо атрибуции не случилось вовсе (000019
-- и insertEvent читают ТОТ ЖЕ ключ payload и проекта с таким именем не нашли),
-- либо атрибуция БЫЛА и её обнулил FK при удалении проекта. В обоих случаях
-- непустой слаг в payload называет проект, которого больше нет, — а это ровно
-- тот единственный вопрос, на который снимок и отвечает: «БЫЛ ли у строки
-- владелец и как его звали». Живой проект под тем же ИМЕНЕМ при этом
-- существовать может, имя переиспользуемо, — но это будет ДРУГОЙ проект, с
-- другим id; следующий абзац именно об этом.
--
-- БЕЗ ПРОВЕРКИ, ЖИВ ЛИ ПРОЕКТ С ТАКИМ СЛАГОМ, — И ЭТО НЕ НЕДОСМОТР. Напрашивается
-- защита «доатрибутировать только если живого проекта с этим слагом нет»: слаг
-- переиспользуем, пересоздание под тем же именем штатный путь, и кажется, что
-- иначе история мёртвого проекта достанется новому арендатору. Не достанется, и
-- проверять нечего: `project_slug` стоит во ВСЕХ трёх местах, которые его
-- читают, — `store.ListEvents`, `store.ListEventsAfter`, коллектор метрик —
-- только в ВЫЧИТАЮЩЕЙ позиции (`project_id is null and project_slug is null`,
-- `project_id is not null or project_slug is null`). Единственный дизъюнкт,
-- который ДАЁТ арендатору видимость, — сравнение `project_id` с id проекта, а
-- эта миграция `project_id` не трогает вовсе: он остаётся NULL. Поэтому
-- проставленный слаг может строку только СПРЯТАТЬ и не может показать её
-- никому, включая проект, пересозданный под тем же именем (у него новый id).
-- Такая защита была бы строго ХУЖЕ бэкфилла: не предотвращая ничего, она
-- оставила бы видимой всей платформе как раз ту историю, чей слаг успели
-- переиспользовать, — то есть сохранила бы утечку #1083 в худшем её случае.
--
-- СПИСКА ВИДОВ ТОЖЕ НЕТ, СОЗНАТЕЛЬНО. Правило структурное и совпадает с тем,
-- что уже читают 000019 и insertEvent; зашитый перечень видов вморозил бы
-- снимок сегодняшнего кода в миграцию, которая бежит по СТАРЫМ данным, и протух
-- бы на первом же новом виде, кладущем `project`. Проверено по всем точкам
-- записи события (grep по insertEvent/InsertEvent): ключ ровно один —
-- `project`, второго написания нет, и везде, где он есть, он называет
-- ВЛАДЕЛЬЦА, а не что-то ещё. Кладут его восемнадцать видов — project_created,
-- project_deleted, environment_deleted, apikey_created, apikey_revoked,
-- apikey_purged, alert_muted, alert_unmuted, allocation_failed, crash_loop,
-- deploy_no_nodes, deploy_started, deploy_activated, deploy_rolled_back,
-- version_disabled (только в ветке superseded), version_registered,
-- version_promoted, fleet_updated. Перечень тут ради проверяемости, а не как
-- условие: в SQL ниже его нет.
--
-- У ДВУХ ВИДОВ ПИСАТЕЛЬ НЕ ОДИН, и это стоит назвать, иначе читатель пойдёт
-- искать payload не туда. `apikey_created`/`apikey_purged` собирает
-- `apiKeyEventPayload` (httpapi/apikeys.go), и он кладёт `project` ТОЛЬКО у
-- привязанного ключа. А у `apikey_revoked` писателей ТРИ: тот же
-- `apiKeyEventPayload` из `DELETE /v1/apikeys/{id}` плюс два каскада —
-- store/projects.go и store/environments.go, — которые строят payload на месте
-- и кладут `project` БЕЗУСЛОВНО (они и выбирают ключи по проекту). Ровно так же
-- двоится `alert_unmuted`: httpapi/alerts.go и каскад удаления проекта.
--
-- ЦЕНА ОШИБКИ НЕСИММЕТРИЧНА, И ЭТО РЕШЕНИЕ, А НЕ УМОЛЧАНИЕ. Единственный
-- ложноположительный случай — слаг, которого не существовало НИКОГДА (опечатка,
-- чужое имя в payload; кейс пинуется в events_orphan_backfill_test.go как
-- `legacy_unknown_slug` со слагом `nope` — тот же слаг, которым
-- `legacy_unknown_slug_event` пинует поведение 000019 по соседству).
-- Такая строка после бэкфилла перестанет считаться платформенной, хотя
-- платформенной она и есть. Мы это ПРИНИМАЕМ: по абзацу выше ошибка может идти
-- только в сторону СОКРЫТИЯ от арендатора, а непривязанное чтение (панель,
-- admin, глобальный ключ) видит строку целиком — аудит не теряется, теряется
-- лишний показ соседу.
--
-- ПУСТАЯ СТРОКА ОТСЕКАЕТСЯ ОТДЕЛЬНО, и это НЕ страховка от сегодняшнего кода.
-- Сегодня пустой слаг не кладёт никто: у `allocation_failed` поле объявлено
-- голой строкой, но запрос с пустым `project` отбивается как `bad_request` выше
-- по обработчику и до записи события не доходит, а у `alert_muted`/
-- `alert_unmuted` поле — указатель, платформенный mute кладёт JSON `null`, и
-- `payload->>'project'` даёт SQL NULL (это ловит `is not null`). Условие стоит
-- потому, что миграция бежит по СТАРЫМ данным, которые писал не сегодняшний код,
-- а цена его отсутствия несимметрична: пустой снимок сделал бы платформенную
-- ПО СУЩЕСТВУ строку «осиротевшей» и спрятал бы её от всех арендаторов — та же
-- сторона ошибки, но уже без всякого основания.
update events
   set project_slug = payload->>'project'
 where project_id is null
   and project_slug is null
   and payload->>'project' is not null
   and payload->>'project' <> '';

-- ЧТО ОСТАЁТСЯ НЕВОССТАНОВИМЫМ — и здесь абсолют 000020 верен. События,
-- атрибутированные только ССЫЛКАМИ на сущности, имени владельца не несут нигде:
-- node_created/revoked/drain/undrain/env_changed/quarantine/down/recovered,
-- node_enrolled/node_cert_renewed, server_failed/recovered/drain, все match_*,
-- deploy_node_pulled, deploy_failed, version_retired, version_disabled в ветке
-- reap_ttl, agent_upgrade*. И список этот НЕ ЗАКРЫТ: ветка `default` в
-- `store.ApplyServerEvent` пишет вид, приехавший ОТ АГЕНТА, как есть — набор
-- таких видов открыт, payload у них `{detail}`, атрибуция только по ссылкам.
-- Каскад удаления проекта уносит ноды, версии и матчи,
-- поэтому ссылка виснет, и после удаления восстанавливать действительно не из
-- чего. Такие строки СОЗНАТЕЛЬНО остаются платформенными: приписать их первому
-- попавшемуся проекту значило бы соврать в аудите. И дыра сузилась по ВИДАМ, а
-- не обязательно по числу строк — сколько их в конкретной базе, эта миграция не
-- знает и знать не может: восстановимые виды это операторские действия (создание
-- проекта, деплой, ключи, флоты), а невосстановимые растут с трафиком — события
-- серверов и матчей пишутся на каждый матч. Дыра сузилась, а не закрылась.
--
-- ПОБОЧНЫЙ ЭФФЕКТ НА МЕТРИКИ, названный вслух. Коллектор (`internal/metrics`)
-- исключает осиротевшие строки из `birdman_events_total`, поэтому этот бэкфилл
-- ОДНОРАЗОВО уменьшит серию `{kind, project=""}`. Из видов, которые читают
-- алерты, слаг в payload кладёт только `crash_loop`. Падение counter'а
-- `increase()` трактует как reset, и ложный залп — ЕСЛИ он вообще случится —
-- имеет порядок числа строк `crash_loop`, остающихся платформенными ПО
-- РОЖДЕНИЮ, а reconcile всегда пишет непустой проект, так что для строк этого
-- кода их нет; нулевая база (#960) при этом держит серию на 0, а не даёт ей
-- исчезнуть.
--
-- ЭТО НЕ СПОРИТ с соседним комментарием в metrics.go («у CrashLoop есть
-- события, не принадлежащие никакому проекту»): там объясняется, почему нулевая
-- база заводит серию с ПУСТЫМ проектом, и заводится она из DESIRED STATE —
-- списка проектов в БД, — а не из фактических строк. Здесь же речь о самих
-- строках, и «не принадлежит проекту» у них означает обнулённый каскадом
-- `project_id`, то есть ОСИРОТЕВШУЮ строку, которую этот же запрос теперь и
-- отсекает.
--
-- И это рассуждение о семантике reset'а, а не замер: живого стека тут нет.
-- Считает его, к тому же, не Prometheus, а vmalert/VictoriaMetrics
-- (infra/roles/birdman_monitoring_dev), у которого своя арифметика reset'а и
-- экстраполяции, — поэтому «порядок числа строк» тут именно порядок, а не
-- точная граница.
-- Вдобавок миграция применяется на СТАРТЕ мастера, то есть на разрыве скрейпа,
-- а гейт свежести (#1063) требует непрерывного `up` на всём окне и гасит
-- CrashLoop на окно после возврата.
-- Направление то же, что выбрала 000020: осиротевшее уходит с
-- метрической поверхности, потому что история удалённого проекта не адресуема
-- ни одним правилом и ни одному дежурному не действие.
