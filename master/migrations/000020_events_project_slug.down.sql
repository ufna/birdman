-- Откат снимка слага владельца события (tracker #1083).
-- Различение «платформенное по рождению» / «осиротевшее» теряется: у осиротевших
-- строк project_id уже null, и обратный шаг имени владельца не знает.
--
-- «Безвозвратно» тут стояло зря и снято в 000021 (tracker #1091): у восемнадцати
-- видов слаг владельца лежит в `payload->>'project'`, поэтому после этого отката
-- повторный накат 000020+000021 восстановит различение для них — но только для
-- них. Строкам, у которых владелец жил в ССЫЛКЕ (node_*, server_*, match_*), он
-- действительно не восстанавливается ничем: каскад унёс сущность.
alter table events drop constraint if exists events_project_named;
alter table events drop column if exists project_slug;
