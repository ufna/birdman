-- Осиротевшее событие отличимо от платформенного (tracker #1083).
--
-- ЧТО СЛОЖИЛОСЬ. Миграция 000019 объявила FK `on delete set null`, и это
-- верное решение: события — append-only аудит, удаление проекта не должно
-- стирать след того, что с ним происходило. Читатели ленты трактуют
-- `project_id is null` как «платформенное событие» и показывают его под ЛЮБЫМ
-- проектным фильтром — тоже верное решение (#955/#968): спрятать бекап или
-- ротацию CA значило бы утверждать, что при выбранном проекте на платформе
-- ничего не происходит. Сложение двух верных решений дало третье, которого
-- никто не выбирал: после удаления проекта A вся его история становится
-- «платформенной» ПОСТФАКТУМ и легально проходит сужение — привязанный ключ
-- проекта B читает её целиком, с hostname'ами нод, image_ref'ами и именами
-- ключей.
--
-- ЧТО ДЕЛАЕМ. Снимок слага владельца в момент ЗАПИСИ. Он переживает
-- `set null`, и три состояния становятся различимы:
--
--   project_id is null  и project_slug is null      — платформенное ПО РОЖДЕНИЮ
--                                                     (бекап, CA, сессия);
--   project_id заполнен и project_slug заполнен     — событие живого проекта;
--   project_id is null  и project_slug заполнен     — ОСИРОТЕВШЕЕ: проект был,
--                                                     и его удалили.
--
-- Читатели показывают под фильтром только первое (store/events.go).
--
-- ПОЧЕМУ СНИМОК СТАВИТСЯ НА ВСТАВКЕ, А НЕ КАСКАДОМ УДАЛЕНИЯ. `set null`
-- срабатывает всегда и не спрашивает, кто удалял: маркер, который проставляет
-- `DeleteProject`, обходится любым вторым путём удаления проекта и порядком
-- операций внутри самой транзакции. Записанный один раз в единственной точке
-- записи (store.insertEvent) — не обходится вовсе.
--
-- СЛАГ НЕ АДРЕСУЕТ ПРОЕКТ. Слаг переиспользуем: пересоздание проекта с тем же
-- именем — штатный путь (переименования нет by design). Поэтому сужение ленты
-- остаётся строго по project_id, а project_slug отвечает ровно на один вопрос —
-- «был ли у этой строки владелец» — и хранит его имя для аудита.
--
-- И ЭТО НЕ ПРОТИВОРЕЧИТ ИНВАРИАНТУ #1079 («после удаления проекта не остаётся
-- строк под его слагом»), хотя выглядит ровно как его нарушение. Тот инвариант
-- про строки, которые слагом АДРЕСУЮТСЯ: match_stats_daily, match_ccu_daily,
-- alert_mutes сравнивают слаг строгим равенством, поэтому переживший проект
-- ряд молча достаётся новому арендатору того же имени. Здесь слагом не
-- адресуется ничто: он читается только как «был владелец / не было», и
-- наследование пинуется отдельным тестом
-- (TestRecreatedProjectDoesNotInheritDeadProjectEvents). Проверка #1079 берёт
-- таблицы по колонке РОВНО `project`, эту не видит — и если кто-то захочет
-- обобщить её до `project%`, читать надо этот абзац, а не заводить исключение.
alter table events add column project_slug text;

-- Бэкфилл живых строк: у них владелец есть, значит его имя обязано быть
-- записано, иначе следующее удаление проекта снова сделает их платформенными.
update events e set project_slug = p.slug from projects p where p.id = e.project_id;

-- Строки, осиротевшие ДО этой миграции, остаются здесь неотличимы от
-- платформенных: проекта уже нет, а снимок ставится только на вставке.
--
-- ЭТА ФОРМУЛИРОВКА БЫЛА ШИРЕ ПРАВДЫ и сужена в 000021 (tracker #1091). Здесь
-- стояло «имя владельца нигде не сохранено, восстанавливать не из чего» — верно
-- для строк, атрибутированных только ССЫЛКАМИ (node_*, server_*, match_*: каскад
-- унёс сущность, ссылка висит), и НЕВЕРНО для восемнадцати видов, которые кладут
-- слаг владельца в `payload->>'project'` — то есть в тот же ключ, из которого
-- читает последняя ветка coalesce'а 000019 и сам insertEvent. Восстановимую
-- часть доатрибутирует 000021; невосстановимая остаётся платформенной
-- сознательно. Дыра сужена, а не закрыта — и сужена она по ВИДАМ, а не
-- обязательно по числу строк: восстановимые виды это операторские действия
-- (создание проекта, деплой, ключи), а невосстановимые растут с трафиком —
-- события матчей и серверов пишутся на каждый матч.

-- Инвариант структурный, а не соглашение о том, как надо писать: строка,
-- назвавшая проект по id, обязана назвать его и по имени. Без этого любой
-- будущий писатель, забывший про снимок, молча вернул бы ровно тот дефект,
-- ради которого заведена колонка, — и заметили бы это только после удаления
-- проекта, то есть на живой утечке.
alter table events add constraint events_project_named
  check (project_id is null or project_slug is not null);
