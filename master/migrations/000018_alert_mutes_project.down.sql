-- Откат проектного измерения mute'ов.
--
-- Схлопывать нечего, в отличие от 000017: PK у alert_mutes синтетический
-- (uuid), уникального ключа на цель (alertname, region) нет вовсе, поэтому две
-- строки, различавшиеся только проектом, после снятия колонки просто
-- сосуществуют — вставка не падает, а upsert берёт активную строку цели через
-- `order by created_at desc limit 1` и дальше работает как в эру до проекта.
--
-- Проектные мьюты при откате РАСШИРЯЮТСЯ до «все проекты», а не удаляются.
-- Это осознанный выбор направления: расширение возвращает ровно доv0-семантику
-- (mute без проектного измерения всегда глушил все проекты), тогда как
-- удаление молча СНЯЛО БЫ подавление — оператор откатил схему и получил
-- звенящий Discord там, где сам поставил заглушку.
--
-- Зеркальные silences откат НЕ переписывает (проверено по коду в ревью #957):
-- reconcile-проход amsilence сверяет у живого active-silence только потерю и
-- дрейф endsAt, матчеры не трогает вовсе — они перестраиваются из строки mute'а
-- лишь при пере-выпуске (правка/повторный POST mute'а, потеря или истечение
-- silence). Поэтому project-матчер живёт в alertmanager до одного из этих
-- событий, и всё это время AM глушит УЖЕ, чем обещает расширенный откатом mute.
-- Направление безопасное — прозвенит лишний алерт соседнего проекта, молча
-- проглочено ничего не будет; кому нужно сразу — достаточно пере-POST'ить mute.
alter table alert_mutes drop column project;
